// Duplicated verbatim in netlify/edge-functions/content-prerender.ts because Netlify
// edge functions run in Deno and cannot import from src/. This file is the source of truth.
export function termSlug(term: string): string {
  return String(term || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/['\u2018\u2019]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80)
    .replace(/-+$/g, "");
}
